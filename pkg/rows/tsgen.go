package rows

import (
	"bytes"
	"encoding/json"
	"fmt"
	"regexp"
	"strings"
	"unicode"
)

// GenerateTS renders the registry as frontend/src/generated/rowSchemas.ts: per type the column
// order, kinds, filter types, predefined values, search fields and the TypeScript shape of the
// cells. cmd/gen-rows writes it and a test fails when the committed file is stale.
func GenerateTS() []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/gen-rows from pkg/rows. DO NOT EDIT.\n")
	b.WriteString("// Regenerate with `go generate ./...` after changing a row spec.\n\n")
	b.WriteString(`export type ColumnKind = 'string' | 'number' | 'time' | 'bool';
export type ColumnFilterType = 'select' | 'regex' | 'numeric' | 'none';

export interface RowSchemaColumn {
    readonly key: string;
    readonly kind: ColumnKind;
    readonly filterType: ColumnFilterType;
    readonly predefined: readonly string[];
    readonly volatile: boolean;
}

export interface RowSchemaSearchField {
    readonly name: string;
    readonly aliases: readonly string[];
}

export interface RowSchema {
    readonly type: string;
    readonly namespaced: boolean;
    readonly schemaVersion: string;
    readonly migrated: true;
    readonly columns: readonly RowSchemaColumn[];
    readonly search: readonly RowSchemaSearchField[];
    readonly presets: readonly string[];
}

`)
	types := Types()
	for _, t := range types {
		spec, _ := Lookup(t)
		fmt.Fprintf(&b, "export interface %s {\n", cellsInterface(t))
		for _, c := range spec.Columns {
			fmt.Fprintf(&b, "    %s: %s;\n", tsKey(c.Key), c.CellType)
		}
		b.WriteString("}\n\n")
	}
	b.WriteString("export const rowSchemas = {\n")
	for _, t := range types {
		spec, _ := Lookup(t)
		fmt.Fprintf(&b, "    %s: {\n", tsKey(t))
		fmt.Fprintf(&b, "        type: %s,\n", jsonString(spec.Type))
		fmt.Fprintf(&b, "        namespaced: %t,\n", spec.Namespaced)
		fmt.Fprintf(&b, "        schemaVersion: %s,\n", jsonString(spec.SchemaVersion()))
		b.WriteString("        migrated: true,\n")
		b.WriteString("        columns: [\n")
		for _, c := range spec.Columns {
			fmt.Fprintf(&b, "            { key: %s, kind: %s, filterType: %s, predefined: %s, volatile: %t },\n",
				jsonString(c.Key), jsonString(string(c.Kind)), jsonString(string(c.FilterType)), jsonStrings(c.Predefined), c.Volatile)
		}
		b.WriteString("        ],\n        search: [\n")
		for _, f := range spec.Search {
			fmt.Fprintf(&b, "            { name: %s, aliases: %s },\n", jsonString(f.Name), jsonStrings(f.Aliases))
		}
		b.WriteString("        ],\n")
		var presets []string
		for _, p := range spec.Presets {
			presets = append(presets, p.Name)
		}
		fmt.Fprintf(&b, "        presets: %s,\n", jsonStrings(presets))
		b.WriteString("    },\n")
	}
	b.WriteString("} as const;\n\n")
	b.WriteString("export type RowSchemaType = keyof typeof rowSchemas;\n\n")
	b.WriteString("export interface RowCellTypes {\n")
	for _, t := range types {
		fmt.Fprintf(&b, "    %s: %s;\n", tsKey(t), cellsInterface(t))
	}
	b.WriteString("}\n")
	return b.Bytes()
}

func jsonString(s string) string {
	// Single quotes, as the frontend style uses; the content never needs more than \\ and \'.
	j, _ := json.Marshal(s)
	inner := string(j[1 : len(j)-1])
	inner = strings.ReplaceAll(inner, `\"`, `"`)
	inner = strings.ReplaceAll(inner, `'`, `\'`)
	return "'" + inner + "'"
}

func jsonStrings(ss []string) string {
	if len(ss) == 0 {
		return "[]"
	}
	parts := make([]string, len(ss))
	for i, s := range ss {
		parts[i] = jsonString(s)
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

var identRe = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

func tsKey(k string) string {
	if identRe.MatchString(k) {
		return k
	}
	return jsonString(k)
}

func cellsInterface(typ string) string {
	var b strings.Builder
	up := true
	for _, r := range typ {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			up = true
			continue
		}
		if up {
			b.WriteRune(unicode.ToUpper(r))
			up = false
		} else {
			b.WriteRune(r)
		}
	}
	return b.String() + "Cells"
}
